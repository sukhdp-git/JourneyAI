<?php
declare(strict_types=1);

namespace App\Controllers;

use App\Core\Request;
use App\Core\Database;
use App\Trading\FlexCard;
use App\Trading\PublicPnl;

/** Public page behind the QR code on a daily flex card: confirms the card came from a journzey.ai journal. */
final class VerifyController extends Controller
{
    public function show(Request $req): never
    {
        $card = FlexCard::find((string) ($req->params['code'] ?? ''));
        if (!$card) {
            $this->notFound();
        }
        header('X-Robots-Tag: noindex, nofollow');
        $this->render('verify', ['card' => $card['payload'], 'checked' => $card['updated_at']], [
            'title' => ['trade' => 'Verified trade card', 'week' => 'Verified trading week card'][$card['payload']['kind'] ?? 'day'] ?? 'Verified trading day card', 'description' => 'This trading day card was generated by journzey.ai from the trader’s journal.', 'path' => '/verify/' . $req->params['code'], 'noindex' => true,
        ]);
    }

    /** Public verified P&L page for a member-created link (/p/{code}). */
    public function pnl(Request $req): never
    {
        $l = PublicPnl::find((string) ($req->params['code'] ?? ''));
        if (!$l) {
            $this->notFound();
        }
        Database::query('UPDATE public_pnl_links SET views = views + 1 WHERE id = :id', ['id' => $l['id']]);
        header('X-Robots-Tag: noindex, nofollow');
        $first = (int) $l['show_name'] ? trim(explode(' ', trim((string) $l['user_name']))[0] ?? '') : '';
        $this->render('pnl', ['l' => $l, 'r' => PublicPnl::report($l), 'first' => $first], [
            'title' => ($first !== '' ? $first . '’s ' : '') . 'verified P&L', 'description' => 'Trading results computed by journzey.ai from the trader’s journal.', 'path' => '/p/' . $l['code'], 'noindex' => true,
        ]);
    }
}
