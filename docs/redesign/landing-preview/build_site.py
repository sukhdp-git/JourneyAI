# Builds the PHP site files for the new landing page from page.src.html (the same source as the preview).
#   python3 docs/redesign/landing-preview/build_site.py
# Writes: public/assets/{css/landing.css, js/landing.js, images/landing/*, fonts/landing/*},
#         app/views/public/{landing.php, partials/landing-owl.php, partials/landing-defs.php}
import pathlib, re, shutil
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
ns = {'pathlib': pathlib, '__file__': str(ROOT / 'docs/brand/logo/build_owl.py')}
exec((ROOT / 'docs/brand/logo/build_owl.py').read_text().split('def svg(')[0], ns)

def eye(x, flip):
    s = -1 if flip else 1
    return (f'<circle cx="{x}" cy="180" r="40" fill="#fff"/><g class="pupil">'
            f'<circle cx="{x+s*3}" cy="183" r="27" fill="url(#iris)"/><circle cx="{x+s*3}" cy="183" r="27" fill="none" stroke="#3a1f92" stroke-width="2.5" opacity=".6"/>'
            f'<circle cx="{x+s*4}" cy="184" r="14.5" fill="#15132a"/><circle cx="{x+s*4-8*s}" cy="172" r="8.5" fill="#fff"/><circle cx="{x+s*4+9*s}" cy="193" r="4" fill="#fff" opacity=".9"/></g>')
ns['eye'] = eye
owl_svg = f'<svg viewBox="20 40 360 330" role="img" aria-label="journzey owl"><g filter="url(#sh)">{ns["owl"](False)}</g></svg>'

src = (HERE / 'page.src.html').read_text()
css = src[src.index('<style>') + 7:src.index('</style>')]
rest = src[src.index('</style>') + 8:]
body, js = rest.rsplit('<script>', 1)
js = js.rsplit('</script>', 1)[0]

# ---- assets
assets = ROOT / 'public/assets'
for d in ('images/landing', 'fonts/landing'):
    (assets / d).mkdir(parents=True, exist_ok=True)
for f in (HERE / 'img').glob('*.webp'):
    shutil.copy(f, assets / 'images/landing' / f.name)
for f in (HERE / 'fonts').glob('*.woff2'):
    shutil.copy(f, assets / 'fonts/landing' / f.name)
faces = '\n'.join(f'@font-face{{font-family:"{n}";src:url("../fonts/landing/{f}") format("woff2");font-weight:200 800;font-style:normal;font-display:swap}}'
                  for n, f in (('Bricolage', 'bricolage.woff2'), ('Geist', 'geist.woff2'), ('GeistMono', 'geist-mono.woff2')))
css = css.replace('{{FONTS}}', faces).replace('.plans{display:grid;grid-template-columns:repeat(3,minmax(0,1fr))', '.plans{display:grid;grid-template-columns:repeat(var(--cols,3),minmax(0,1fr))')
(assets / 'css/landing.css').write_text('/* journzey.ai landing page. Built from docs/redesign/landing-preview/page.src.html by build_site.py. */' + css)
(assets / 'js/landing.js').write_text('/* journzey.ai landing page behaviour. Built from docs/redesign/landing-preview/page.src.html by build_site.py. */\n' + js.strip() + '\n')

# ---- partials
views = ROOT / 'app/views/public'
(views / 'partials/landing-owl.php').write_text('<?php /** The owl mascot (eyes follow the pointer). Generated by docs/redesign/landing-preview/build_site.py */ ?>' + owl_svg)
(views / 'partials/landing-defs.php').write_text('<?php /** Gradients and filters used by the owl. Generated by docs/redesign/landing-preview/build_site.py */ ?>' + ns['DEFS'])

# ---- view
b = body.strip()
b = b.replace('{{DEFS}}', "<?= View::partial('public/partials/landing-defs') ?>")
for k in ('OWL_NAV', 'OWL_NAV2', 'OWL_HERO', 'OWL_CTA'):
    b = b.replace('{{' + k + '}}', "<?= View::partial('public/partials/landing-owl') ?>")
b = re.sub(r'src="img/([a-z0-9\-]+)\.webp"', lambda m: f'src="<?= e(asset(\'images/landing/{m.group(1)}.webp\')) ?>"', b)
for path in ('/signup', '/login', '/learn', '/about', '/contact', '/grievance-officer', '/privacy-policy', '/terms-and-conditions', '/disclaimer'):
    b = b.replace(f'href="{path}"', f'href="<?= e(url(\'{path}\')) ?>"')

# pricing: free card stays curated, paid cards come from the plans table
a, z = b.index('<!--PLANS-->'), b.index('<!--/PLANS-->')
plans_html = b[a:z]
free_card = plans_html[plans_html.index('<article class="plan rv">'):plans_html.index('<article class="plan pro')]
free_card = free_card.replace('href="<?= e(url(\'/signup\')) ?>"', 'href="<?= e(url(\'/signup\')) ?>"')
check = '<svg viewBox="0 0 24 24"><path d="M5 12.5l4.5 4.5L19 7.5"/></svg>'
dyn = f'''<div class="plans" style="--cols:<?= count($cards) + 1 ?>">
      {free_card.strip()}
      <?php foreach ($cards as $i => $c): $m = $c['m']; $y = $c['y']; $feat = parse_lines($m['features'], ['title']); $feat = $feat ?: []; ?>
      <article class="plan<?= (int) $m['is_featured'] ? ' pro' : '' ?> rv" style="--d:<?= $i + 1 ?>"><h3><?= e($m['name']) ?><?php if ((int) $m['is_featured']): ?> <span class="pill">Most popular</span><?php endif; ?></h3><p class="for"><?= e((string) ($m['tagline'] ?? '')) ?></p>
        <div class="price"><?php if ($y): ?><span class="swap" data-m="<?= e($fmt($m['price'], $m['currency'])) ?>" data-ay="<?= e($fmt($y['price'], $y['currency'])) ?>"><?= e($fmt($m['price'], $m['currency'])) ?></span><small class="swap" data-m="/ <?= e($m['interval_label']) ?>" data-ay="/ <?= e($y['interval_label']) ?>">/ <?= e($m['interval_label']) ?></small><?php else: ?><?= e($fmt($m['price'], $m['currency'])) ?><small>/ <?= e($m['interval_label']) ?></small><?php endif; ?></div>
        <ul><?php foreach ($feat as $f): ?><li>{check}<?= e($f['title']) ?></li><?php endforeach; ?></ul>
        <a class="btn <?= (int) $m['is_featured'] ? 'btn-solid' : 'btn-line' ?>" href="<?= e($cta($m)) ?>"<?php if ($y): ?> data-hm="<?= e($cta($m)) ?>" data-hy="<?= e($cta($y)) ?>"<?php endif; ?>>Get <?= e($m['name']) ?></a></article>
      <?php endforeach; ?>
    </div>'''
b = b[:a] + dyn + b[z + len('<!--/PLANS-->'):]
b = re.sub(r'<!--SEG-->(.*?)<!--/SEG-->', lambda m: '<?php if ($hasYearly): ?>' + m.group(1) + '<?php endif; ?>', b, flags=re.S)

# footer legal block follows Control Panel settings
foot = '''<div class="foot-b">
    <?php if (setting_on('sebi_notice_enabled', true)): ?><p><?= e(setting('legal_entity') ?: setting('site_name', 'journzey.ai')) ?> is a trading journal and education platform. We are not registered with SEBI as an investment adviser or research analyst and do not give buy or sell recommendations, tips or signals.</p><?php endif; ?>
    <p>Trading involves substantial risk of loss. Screens shown use demo data.<?= setting('footer_disclaimer') !== '' ? ' ' . e(setting('footer_disclaimer')) : '' ?></p>
    <ul class="foot-legal"><li>&copy; <?= date('Y') ?> <?= e(setting('site_name', 'journzey.ai')) ?></li><?php if ($consentOn): ?><li><button type="button" onclick="document.cookie='jz_consent=; Max-Age=0; Path=/';location.reload()">Cookie settings</button></li><?php endif; ?></ul>
  </div>'''
b = re.sub(r'<!--FOOTB-->.*?<!--/FOOTB-->', lambda m: foot, b, flags=re.S)

head = r'''<?php
use App\Core\View;
/** New landing page (Control Panel -> General -> "Use the new landing page"). Generated by docs/redesign/landing-preview/build_site.py from page.src.html. */
$me = member();
$all = App\Trading\Payments::plans();
$cards = [];
foreach ($all as $p) {
    if ((int) $p['interval_days'] < 360) {
        $cards[] = ['m' => $p, 'y' => null];
    }
}
foreach ($all as $p) {
    if ((int) $p['interval_days'] >= 360) {
        $base = trim((string) preg_replace('/\s*(annual|yearly)\s*$/i', '', $p['name']));
        $placed = false;
        foreach ($cards as $k => $c) {
            if (!$c['y'] && strcasecmp($c['m']['name'], $base) === 0) {
                $cards[$k]['y'] = $p;
                $placed = true;
                break;
            }
        }
        if (!$placed) {
            $cards[] = ['m' => $p, 'y' => null];
        }
    }
}
$hasYearly = (bool) array_filter($cards, fn ($c) => $c['y']);
$fmt = fn ($v, $c) => preg_replace('/\\.00$/', '', money($v, $c));
$cta = fn (array $p) => url($me ? '/checkout/' . $p['slug'] : '/signup?plan=' . $p['slug']);
$consentOn = setting_on('cookie_banner_enabled', true) && (setting_on('gtm_enabled') || setting_on('ga_enabled') || setting_on('pixel_enabled'));
?>
'''
(views / 'landing.php').write_text(head + b + '\n')
print('built', len(css) // 1024, 'KB css,', len(js) // 1024, 'KB js,', len(b) // 1024, 'KB view')
