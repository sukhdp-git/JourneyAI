// Generates database/seed.sql from packages/shared (same source as the ORM seed and onboarding demo flow).
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { INSTRUMENTS, STRATEGY_TEMPLATES, DEMO_ACCOUNT, DEMO_JOURNALS, generateDemoTrades, computeTradeMath, getInstrument } from '@journzey/shared';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `ARRAY[${a.map(q).join(', ')}]::text[]`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;
const out = [];

out.push(`-- journzey.ai — seed data
-- GENERATED by \`npm run db:seed-sql\` from packages/shared. Do not edit by hand.
-- Idempotent. Apply after the schema:  psql "$DATABASE_URL" -f database/seed.sql
--
-- 1. Reference data: strategy templates + supported instruments.
-- 2. journzey_load_demo_data(user_id): attaches the optional DEMO DATA set to an EXISTING user
--    (created by real Google sign-in). No users or fake identities are created here.

BEGIN;
`);
out.push('-- Strategy templates');
STRATEGY_TEMPLATES.forEach((t, i) => {
  out.push(`INSERT INTO strategy_templates (name, description, target_rr, checklist, sort_order) VALUES (${q(t.name)}, ${q(t.description)}, ${t.targetRr}, ${json(t.checklist)}, ${i})
  ON CONFLICT (name) DO UPDATE SET description = EXCLUDED.description, target_rr = EXCLUDED.target_rr, checklist = EXCLUDED.checklist, sort_order = EXCLUDED.sort_order;`);
});
out.push('\n-- Supported instruments');
for (const i of INSTRUMENTS) {
  out.push(`INSERT INTO instruments (symbol, display_name, asset_class, base_currency, quote_currency, contract_size, tick_size, tick_value, pip_size, decimals, aliases) VALUES (${q(i.symbol)}, ${q(i.displayName)}, ${q(i.assetClass)}, ${q(i.baseCurrency)}, ${q(i.quoteCurrency)}, ${i.contractSize}, ${i.tickSize}, ${i.tickValue}, ${i.pipSize}, ${i.decimals}, ${arr(i.aliases)})
  ON CONFLICT (symbol) DO UPDATE SET display_name = EXCLUDED.display_name, asset_class = EXCLUDED.asset_class, base_currency = EXCLUDED.base_currency, quote_currency = EXCLUDED.quote_currency, contract_size = EXCLUDED.contract_size, tick_size = EXCLUDED.tick_size, tick_value = EXCLUDED.tick_value, pip_size = EXCLUDED.pip_size, decimals = EXCLUDED.decimals, aliases = EXCLUDED.aliases;`);
}

const trades = generateDemoTrades();
const tradeRows = trades.map((t) => {
  const m = computeTradeMath({ ...t, accountCurrency: DEMO_ACCOUNT.currency });
  return `      (p_user_id, v_account, ${q(t.executedAt)}::timestamptz, ${q(t.closedAt)}::timestamptz, ${q(t.symbol)}, ${q(getInstrument(t.symbol).assetClass)}, ${q(t.side)}, 'CLOSED', ${t.entryPrice}, ${t.exitPrice}, ${t.stopLoss}, ${t.takeProfit}, ${t.lotSize}, ${m.pnl}, ${m.rr}, ${m.riskAmount}, (SELECT id FROM strategies WHERE user_id = p_user_id AND lower(name) = lower(${q(t.strategy)})), ${q(t.setupTag)}, ${q(t.session)}, ${q(t.emotion)}, ${q(t.mistakeTag)}, ${t.rulesFollowed}, ${q(t.notes)}, 'DEMO')`;
});
const journalRows = DEMO_JOURNALS.map(
  (j) => `      (p_user_id, ${q(j.journalDate)}::date, ${j.compliance}, ${q(j.emotionalState)}, ${j.disciplineRating}, ${q(`[DEMO DATA] ${j.reflection}`)}, ${q(j.keyLesson)}, true)`,
);

out.push(`
-- Optional DEMO DATA loader (${trades.length} trades Aug–Oct 2026, ${DEMO_JOURNALS.length} journal entries).
-- Usage: SELECT journzey_load_demo_data('<existing user uuid>');
CREATE OR REPLACE FUNCTION journzey_load_demo_data(p_user_id uuid) RETURNS uuid
LANGUAGE plpgsql AS $$
DECLARE
  v_account uuid;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM users WHERE id = p_user_id) THEN
    RAISE EXCEPTION 'user % does not exist', p_user_id;
  END IF;
  -- Remove any previous demo data for this user (same as "Reset Demo Data").
  DELETE FROM trading_accounts WHERE user_id = p_user_id AND sample_data;
  DELETE FROM journal_entries WHERE user_id = p_user_id AND demo;
  -- Ensure the user's playbooks exist.
  INSERT INTO strategies (user_id, name, description, target_rr, checklist)
    SELECT p_user_id, name, description, target_rr, checklist FROM strategy_templates
    ON CONFLICT DO NOTHING;
  INSERT INTO trading_accounts (user_id, account_name, broker_name, currency, starting_capital, current_capital, demo, sample_data)
    VALUES (p_user_id, ${q(DEMO_ACCOUNT.accountName)}, ${q(DEMO_ACCOUNT.brokerName)}, ${q(DEMO_ACCOUNT.currency)}, ${DEMO_ACCOUNT.startingCapital}, ${DEMO_ACCOUNT.startingCapital}, true, true)
    RETURNING id INTO v_account;
  INSERT INTO trades (user_id, trading_account_id, executed_at, closed_at, symbol, asset_class, side, status, entry_price, exit_price, stop_loss, take_profit, lot_size, pnl, rr, risk_amount, strategy_id, setup_tag, session, emotion, mistake_tag, rules_followed, notes, source) VALUES
${tradeRows.join(',\n')};
  INSERT INTO journal_entries (user_id, journal_date, compliance, emotional_state, discipline_rating, reflection, key_lesson, demo) VALUES
${journalRows.join(',\n')}
    ON CONFLICT DO NOTHING;
  UPDATE trading_accounts SET current_capital = starting_capital + COALESCE((SELECT SUM(pnl) FROM trades WHERE trading_account_id = v_account), 0)
    WHERE id = v_account;
  RETURN v_account;
END;
$$;

COMMIT;
`);
writeFileSync(path.join(root, 'database/seed.sql'), out.join('\n'));
console.log(`wrote database/seed.sql (${STRATEGY_TEMPLATES.length} templates, ${INSTRUMENTS.length} instruments, ${trades.length} demo trades)`);
